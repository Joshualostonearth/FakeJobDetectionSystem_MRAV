"""
Global / offline XAI report for M4 (Objective 5) -> results/xai_global_report.md

  1. Top 30 words each way for the M1 classifier: exact linear attributions aggregated to
     whitespace tokens (word + char n-grams), summed per posting and averaged over the 3,151
     test postings (field labels such as "description:" excluded).
  2. Top word n-gram features and metadata features by mean contribution.
  3. Five worked examples picked from the parity fixture: a true positive, a false positive,
     a false negative, a REVIEW-zone case and the most conflict-heavy case.

    python scripts/xai_global_report.py
"""

from __future__ import annotations

import sys
import time
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

import mravplus_infer as m4  # noqa: E402
from xai import explain, linear_explainer  # noqa: E402
from xai.render import display_term  # noqa: E402

OUT = PROJECT_ROOT / "results" / "xai_global_report.md"
FIXTURE = PROJECT_ROOT / "tests" / "fixtures" / "test_predictions_mravplus.csv"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    t0 = time.time()
    det = m4.M4Detector()
    lin = linear_explainer(det)
    _, _, te = m4.load_emscad_splits()
    ref = pd.read_csv(FIXTURE)
    assert (ref.y.values == te.fraudulent.values).all()
    recs = te.drop(columns=["text"]).to_dict("records")
    labels = {f"{c}:" for c in det.FIELDS}

    tok_sum = defaultdict(float)
    tok_docs = defaultdict(int)
    meta_sum = defaultdict(float)
    for rec in recs:
        row, _ = det.build_row("", rec)
        parts = lin.contributions(row)
        for t, v in lin.token_scores(row, parts).items():
            if t not in labels:
                tok_sum[t] += v
                tok_docs[t] += 1
        for j, v in zip(parts["idx"][parts["meta_mask"]], parts["contrib"][parts["meta_mask"]]):
            meta_sum[str(lin.meta_names[j - lin.n_text])] += v
    N = len(recs)
    mean_tok = {t: v / N for t, v in tok_sum.items()}

    # word n-gram features: exact mean contribution = w_bar * mean tf-idf value
    rows_all = [det.build_row("", r)[0] for r in recs]
    X = det.m1_matrix(rows_all)
    mean_x = np.asarray(X[:, : lin.n_word].mean(axis=0)).ravel()
    feat_mean = lin.w[: lin.n_word] * mean_x
    order = np.argsort(feat_mean)
    word_names = [n.split("__", 1)[1] for n in lin.names[: lin.n_word]]

    top_f = sorted(mean_tok.items(), key=lambda kv: -kv[1])[:30]
    top_l = sorted(mean_tok.items(), key=lambda kv: kv[1])[:30]
    t_global = time.time() - t0

    # worked examples
    zone, pred, y, conflict = ref.zone.values, ref.pred_M4.values, ref.y.values, ref.conflict.values
    picks = [
        ("True positive (fraud, flagged)", int(np.where((y == 1) & (pred == 1) & (zone == 2))[0][0])),
        ("False positive (legit, flagged)", int(np.where((y == 0) & (pred == 1))[0][0])),
        ("False negative (fraud, missed)", int(np.where((y == 1) & (pred == 0))[0][0])),
        ("REVIEW-zone case (DistilBERT consulted)", int(np.where(zone == 1)[0][0])),
        ("Most conflict-heavy case", int(np.argmax(conflict))),
    ]

    L = ["# M4 global XAI report (Objective 5)", "",
         f"Generated by `python scripts/xai_global_report.py` on the {N}-posting EMSCAD test split "
         f"(seed 42). Runtime: RUNTIME_PLACEHOLDER s on CPU (global attributions {t_global:.0f} s).", "",
         "EMSCAD anonymised e-mail addresses, phone numbers and URLs as `#email_<hash>#`-style tokens; they "
         "are shown here as `#email#` / `#phone#` / `#url#`. Real posters contain real addresses, which the model "
         "never saw in this form.", "",
         "All attributions are exact for the M1 TF-IDF SVM: contribution = averaged LinearSVC weight x "
         "feature value, and contributions + intercept equal the averaged decision function. Positive = "
         "towards FAKE. Word scores include the char n-grams that fall inside each word. Means are over all "
         "test postings (a word absent from a posting contributes 0 to it).", "",
         "## 1. Top 30 words towards FAKE (mean contribution per posting)", "",
         md_table(["#", "word", "mean contribution", "postings containing it"],
                  [(i + 1, f"`{display_term(t)}`", f"{v:+.5f}", tok_docs[t]) for i, (t, v) in enumerate(top_f)]), "",
         "## 2. Top 30 words towards REAL (mean contribution per posting)", "",
         md_table(["#", "word", "mean contribution", "postings containing it"],
                  [(i + 1, f"`{display_term(t)}`", f"{v:+.5f}", tok_docs[t]) for i, (t, v) in enumerate(top_l)]), "",
         "## 3. Word n-gram features (mean contribution, exact)", "",
         md_table(["towards FAKE", "mean", "towards REAL", "mean"],
                  [(f"`{display_term(word_names[a])}`", f"{feat_mean[a]:+.5f}", f"`{display_term(word_names[b])}`", f"{feat_mean[b]:+.5f}")
                   for a, b in zip(order[::-1][:15], order[:15])]), "",
         "## 4. Metadata features (mean contribution per posting)", "",
         md_table(["feature", "mean contribution"],
                  [(f"`{k}`", f"{v / N:+.5f}") for k, v in sorted(meta_sum.items(), key=lambda kv: -abs(kv[1]))[:15]]), "",
         "Note: `*_Unknown` metadata (field missing) mostly pushes towards FAKE. Poster / OCR input has no "
         "structured fields, so it always carries these contributions unless the user fills the fields in.", "",
         "## 5. Worked examples", ""]

    for title, i in picks:
        rec = recs[i]
        res = det.predict("", rec)
        x = explain(det, "", rec, res, with_ig=True, ig_steps=50)
        L += [f"### {title} - test row {i}", "",
              f"- Title: {m4._as_text(rec.get('title'))!s}",
              f"- True label: {'FRAUD' if rec['fraudulent'] else 'LEGIT'}; M4: "
              f"{'FAKE' if res['predicted_fraud'] else 'NOT FAKE'}, P(fraud) {res['p_fake']:.3f}, zone {res['zone']}, "
              f"conflict K {res['conflict']:.3f}",
              f"- Summary (template): {x['summary']['text']}",
              "- Top fraud-leaning words: " + ", ".join(f"`{display_term(d['term'])}` {d['contribution']:+.3f}" for d in x["m1"]["top_fraud_terms"][:6]),
              "- Top legit-leaning words: " + ", ".join(f"`{display_term(d['term'])}` {d['contribution']:+.3f}" for d in x["m1"]["top_legit_terms"][:6]),
              "- Metadata: " + ", ".join(f"`{d['feature']}` {d['contribution']:+.3f}" for d in x["m1"]["metadata"][:4]),
              "", md_table(["source", "says P(fraud)", "mass R / F / U", "effect on P(fraud) (leave-one-out)"],
                           [(s["label"], "-" if s["says_p_fake"] is None else f"{s['says_p_fake']:.3f}",
                             f"{s['mass']['REAL']:.3f} / {s['mass']['FAKE']:.3f} / {s['mass']['UNCERTAIN']:.3f}",
                             "-" if s["effect_on_p_fake"] is None else f"{s['effect_on_p_fake'] * 100:+.1f} pts")
                            for s in x["dst"]["sources"]]), ""]
        if x["distilbert"]:
            b = x["distilbert"]
            L += [f"- DistilBERT: P(fraud) {res['p_distilbert']:.3f}; gate text {b['gate_weights']['text']:.2f} / "
                  f"metadata {b['gate_weights']['metadata']:.2f}; IG completeness residual "
                  f"{b['completeness_residual']:+.4f} ({b['completeness_relative']:.2%})",
                  "- IG fraud-leaning words: " + ", ".join(f"`{w['word']}` {w['attribution']:+.3f}" for w in b["top_fraud_words"][:6]),
                  "- IG legit-leaning words: " + ", ".join(f"`{w['word']}` {w['attribution']:+.3f}" for w in b["top_legit_words"][:6]), ""]
    text = "\n".join(L) + "\n"
    OUT.write_text(text.replace("RUNTIME_PLACEHOLDER", f"{time.time() - t0:.0f}"), encoding="utf-8")
    print(f"written {OUT} in {time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
