"""
Red-flag rules (red_flags.py) -> results/red_flags_report.md

  1. Hit rate of each rule on all EMSCAD postings, legit vs fraudulent (false alarms vs catches).
     EMSCAD emails are masked, so the free-mail rule cannot fire there.
  2. Optional: the real-world fake jobs collected on the fake-job-samples branch
     (data/real_world_fake_jobs). Text path for every sample, OCR path for every image.
     The rules were written while looking at these samples, so this part shows the rules work
     on them; it is not an independent test.

    python scripts/red_flags_report.py [path/to/real_world_fake_jobs]
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from entity_extractor import extract_entities  # noqa: E402
from red_flags import find_red_flags  # noqa: E402

EMSCAD = PROJECT_ROOT / "data" / "fake_job_postings.csv"
OUT = PROJECT_ROOT / "results" / "red_flags_report.md"
TEXT_COLS = ["title", "company_profile", "description", "requirements", "benefits"]


def emscad_section() -> list:
    df = pd.read_csv(EMSCAD)
    df["text"] = df[TEXT_COLS].fillna("").agg("\n".join, axis=1)
    n = df["fraudulent"].value_counts().to_dict()
    hits = {0: Counter(), 1: Counter()}
    any_hit = Counter()
    legit_examples = {}
    for text, y in zip(df["text"], df["fraudulent"]):
        flags = find_red_flags(text, extract_entities(text))
        for f in flags:
            hits[y][f["id"]] += 1
            if y == 0:
                legit_examples.setdefault(f["id"], []).append(f["evidence"])
        any_hit[y] += bool(flags)

    lines = ["## 1. EMSCAD (all postings)", "",
             f"{n[0]:,} legitimate and {n[1]:,} fraudulent postings (title, company profile, description, "
             "requirements, benefits).", "",
             "| Rule | Legit hits (false alarms) | Fraud hits |", "|---|---|---|"]
    for rid in sorted(set(hits[0]) | set(hits[1])):
        lines.append(f"| `{rid}` | {hits[0][rid]} ({hits[0][rid] / n[0]:.2%}) | {hits[1][rid]} ({hits[1][rid] / n[1]:.2%}) |")
    lines.append(f"| **any rule** | {any_hit[0]} ({any_hit[0] / n[0]:.2%}) | {any_hit[1]} ({any_hit[1] / n[1]:.2%}) |")
    lines += ["", "EMSCAD fraud is mostly fake job ads, not pay-to-join, cheque or chat-app scams, so the rules "
              "rarely fire on it; they are meant for the scams M4 was not trained on.", "",
              "False-alarm evidence on legitimate postings (first 5 per rule):", ""]
    for rid, ev in sorted(legit_examples.items()):
        lines.append(f"- `{rid}`: " + "; ".join(f"\"{e}\"" for e in ev[:5]))
    return lines


def real_world_section(samples_dir: Path) -> list:
    import pipeline_bridge as pb

    items = json.loads((samples_dir / "fake_jobs.json").read_text())

    def row(name, image, text):
        try:
            r = pb.handle_ui_submission(image, text, with_xai=False)
        except ValueError:
            return f"| {name} | rejected (no job offer found) | | | |", None
        ids = ", ".join(f["id"] for f in r["red_flags"]) or "-"
        return (f"| {name} | {r['m4_risk_level']} | {r['final_verdict']} · {r['risk_level']} | "
                f"{r['p_fake']:.2f} | {ids} |"), r

    lines = ["", f"## 2. Real-world fake jobs ({samples_dir.name})", "",
             "All samples are confirmed scams. Not an independent test: the rules were written with these in view.", ""]
    for title, cases in [("Text path", [(it["offer_id"], None, it["text"]) for it in items]),
                         ("Image path (OCR)", [(p.name, str(p), "") for p in sorted((samples_dir / "images").iterdir())])]:
        lines += [f"### {title}", "", "| Sample | M4 risk | Shown (verdict · risk) | P(fraud) | Red flags |",
                  "|---|---|---|---|---|"]
        raised = 0
        for name, image, text in cases:
            line, r = row(name, image, text)
            lines.append(line)
            if r:
                raised += r["m4_risk_level"] != r["risk_level"]
        lines += ["", f"The red flags raised the risk level for {raised} of {len(cases)}.", ""]
    return lines


def main():
    lines = ["# Red-flag rules report", "",
             "Generated by `scripts/red_flags_report.py`. The rules (`red_flags.py`) never change M4's verdict or "
             "P(fraud); a hit raises the risk level one step (LOW -> MEDIUM: call recommended; MEDIUM -> HIGH: call starts automatically).", ""]
    lines += emscad_section()
    if len(sys.argv) > 1:
        lines += real_world_section(Path(sys.argv[1]))
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
