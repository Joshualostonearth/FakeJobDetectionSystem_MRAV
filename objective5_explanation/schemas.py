"""
schemas.py — Pydantic models for Objective 5: Explanation Module.

The EvidenceSheet is the single source of truth handed to the LLM. Every
statement in the final ExplanationReport must cite fact_ids from that sheet,
so the explanation can be traced back to the pipeline's actual outputs.
"""

from typing import List, Literal, Optional

from pydantic import BaseModel, Field

Verdict = Literal["Real", "Fake", "Unable to Verify"]
DecisionPath = Literal["CONFIDENCE_PATH", "VOICE_PATH"]
Stance = Literal["supports_real", "supports_fake", "neutral"]


class EvidenceFact(BaseModel):
    """One atomic, citable fact taken directly from a pipeline output."""

    fact_id: str = Field(..., description="Citable ID, e.g. S1 (source), D1 (DST), K1 (conflict), F1 (flag), V1 (voice)")
    category: Literal["claim", "source", "dst", "conflict", "flag", "voice", "decision"]
    text: str = Field(..., description="Plain-language statement of the fact, including its exact values")
    stance: Stance = "neutral"


class Contradiction(BaseModel):
    """A pair (or group) of facts that point in opposite directions."""

    fact_ids: List[str]
    text: str


class EvidenceSheet(BaseModel):
    """Grounded summary of everything the pipeline produced for one offer."""

    offer_id: str
    decision_path: DecisionPath
    verdict: Verdict
    raw_verdict: str = Field(..., description="Verdict label as produced upstream (Objective 4 or 3)")
    confidence: Optional[float] = Field(default=None, description="Calibrated P(Real) on the confidence path")
    provisional: bool = False
    override_reason: Optional[str] = None
    facts: List[EvidenceFact] = Field(default_factory=list)
    contradictions: List[Contradiction] = Field(default_factory=list)

    def fact_ids(self) -> set:
        return {f.fact_id for f in self.facts}

    def get(self, fact_id: str) -> Optional[EvidenceFact]:
        return next((f for f in self.facts if f.fact_id == fact_id), None)


class ReportPoint(BaseModel):
    """One sentence of the explanation plus the facts it is grounded in."""

    text: str
    cites: List[str] = Field(default_factory=list)


class ExplanationReport(BaseModel):
    """Final Objective 5 output: a readable report grounded in the evidence sheet."""

    offer_id: str
    decision_path: DecisionPath
    verdict: Verdict
    confidence: Optional[float] = None
    provisional: bool = False
    summary: str
    key_evidence: List[ReportPoint] = Field(default_factory=list)
    contradictions: List[ReportPoint] = Field(default_factory=list)
    recommendation: str
    generated_by: Literal["llm", "template"]
    model: Optional[str] = None
    grounding_issues: List[str] = Field(
        default_factory=list,
        description="LLM statements that were rejected because they were not grounded in the evidence sheet",
    )
    evidence_sheet: EvidenceSheet

    def to_text(self) -> str:
        """Render the report as plain text for the CLI or a Streamlit text area."""
        path_label = {
            "CONFIDENCE_PATH": "Calibrated confidence (Objective 4)",
            "VOICE_PATH": "Voice verification (Objective 3)",
        }[self.decision_path]

        lines = ["=" * 70, "EXPLANATION REPORT (Objective 5)", "=" * 70]
        lines.append(f"Offer        : {self.offer_id}")
        lines.append(f"Verdict      : {self.verdict.upper()}" + ("  [PROVISIONAL]" if self.provisional else ""))
        lines.append(f"Decided by   : {path_label}")
        if self.confidence is not None:
            lines.append(f"P(Real)      : {self.confidence:.2%}")
        lines.append("")
        lines.append("Summary:")
        lines.append(f"  {self.summary}")

        def _points(title: str, points: List[ReportPoint]):
            lines.append("")
            lines.append(f"{title}:")
            if not points:
                lines.append("  - None")
            for p in points:
                cite = f"  [{', '.join(p.cites)}]" if p.cites else ""
                lines.append(f"  - {p.text}{cite}")

        _points("Key evidence", self.key_evidence)
        _points("Contradictions", self.contradictions)

        lines.append("")
        lines.append("Recommendation:")
        lines.append(f"  {self.recommendation}")

        lines.append("")
        lines.append("Evidence referenced:")
        for fact in self.evidence_sheet.facts:
            lines.append(f"  [{fact.fact_id}] {fact.text}")

        lines.append("")
        source = f"LLM ({self.model})" if self.generated_by == "llm" else "deterministic template"
        lines.append(f"Generated by : {source}")
        if self.grounding_issues:
            lines.append(f"Rejected     : {len(self.grounding_issues)} ungrounded LLM statement(s)")
        lines.append("=" * 70)
        return "\n".join(lines)
