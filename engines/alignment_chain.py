"""
M-RAV Inspired Verbalized Alignment — Step 5 of the Credibility Filtration Layer.

Following Stage 2 of the M-RAV architecture, raw computational scores are
converted into a verbalized explanation generated by an LLM. This structures
the reasoning so downstream models can interpret WHY evidence agrees or
disagrees with the offer claims.

The LLM produces a structured (Hypothesis, Explanation, Consistency Score)
triple for each (offer, document) pair.
"""

import os
import re

from dotenv import load_dotenv

from key_pool import key_pool
from schemas.input_schema import JobOfferEntities, VectorDocument
from schemas.credibility_schema import MRAVTriple

load_dotenv()

OLLAMA_MODEL: str = os.getenv("OLLAMA_MODEL", "ministral-3")


def _build_alignment_prompt(entities: JobOfferEntities, doc: VectorDocument) -> str:
    """
    Construct the alignment prompt that asks the LLM to evaluate
    consistency between the job offer claims and a retrieved evidence document.
    """
    doc_type_context = "Legitimate Baseline Requirements" if doc.metadata.fraudulent == 0 else "Scam Report Content"
    return f"""Evaluate the consistency between the Job Offer Claim and the Retrieved Evidence Document.
If the retrieved record is a "{doc_type_context}", compare the offer's claimed salary, domain, and requirements against it.

Claimed Company: {entities.company_name}
Claimed Domain: {entities.domain_or_website or "N/A"}
Claimed Role: {entities.job_role}
Claimed Location: {entities.location or "N/A"}
Contact Email/Phone: {entities.email_or_phone or "N/A"}

Retrieved Record ({doc_type_context}, source: {doc.metadata.source_type}, similarity: {doc.similarity_score:.2f}):
{doc.content}

Provide output in the following structured format:
<HYPOTHESIS>: [State whether the retrieved evidence "Confirms", "Contradicts", or is "Neutral" to the offer claims]
<EXPLANATION>: [Describe specific field mismatches such as domain age, suspicious contact info, or salary discrepancies]
<CONSISTENCY_SCORE>: [Assign a score from 0.0 (total contradiction) to 1.0 (exact match)]

<RESPONSE>:"""


def _parse_alignment_response(raw_response: str) -> MRAVTriple:
    """
    Parse the LLM's response into a structured MRAVTriple.

    Falls back gracefully if parsing fails:
    - hypothesis defaults to "Neutral"
    - explanation defaults to the raw response text
    - consistency_score defaults to 0.5
    """
    hypothesis = "Neutral"
    explanation = raw_response.strip()
    consistency_score = 0.5

    # Extract hypothesis
    hyp_match = re.search(
        r"<HYPOTHESIS>\s*:?\s*(.+?)(?:\n|<EXPLANATION>|$)",
        raw_response,
        re.IGNORECASE | re.DOTALL,
    )
    if hyp_match:
        hyp_text = hyp_match.group(1).strip()
        # Normalize to one of the three canonical values
        hyp_lower = hyp_text.lower()
        if "confirm" in hyp_lower:
            hypothesis = "Confirms"
        elif "contradict" in hyp_lower:
            hypothesis = "Contradicts"
        else:
            hypothesis = "Neutral"

    # Extract explanation
    exp_match = re.search(
        r"<EXPLANATION>\s*:?\s*(.+?)(?:\n<CONSISTENCY_SCORE>|$)",
        raw_response,
        re.IGNORECASE | re.DOTALL,
    )
    if exp_match:
        explanation = exp_match.group(1).strip()

    # Extract consistency score
    score_match = re.search(
        r"<CONSISTENCY_SCORE>\s*:?\s*([\d.]+)",
        raw_response,
        re.IGNORECASE,
    )
    if score_match:
        try:
            parsed_score = float(score_match.group(1))
            # Clamp to [0.0, 1.0]
            consistency_score = max(0.0, min(1.0, parsed_score))
        except ValueError:
            pass  # Keep default 0.5

    return MRAVTriple(
        hypothesis=hypothesis,
        explanation=explanation,
        consistency_score=consistency_score,
    )


def generate_alignment_triple(
    entities: JobOfferEntities,
    doc: VectorDocument,
) -> MRAVTriple:
    """
    Generate an M-RAV alignment triple for a (job offer, evidence document) pair.

    Sends a structured prompt to the local Ollama LLM and parses the response
    into a (Hypothesis, Explanation, Consistency Score) triple.

    Args:
        entities: Extracted entities from the job offer letter.
        doc: A retrieved evidence document from FAISS.

    Returns:
        An MRAVTriple containing the LLM's structured evaluation.
    """
    prompt = _build_alignment_prompt(entities, doc)

    def api_call(client):
        try:
            response = client.chat.completions.create(
                model=OLLAMA_MODEL,
                messages=[{"role": "user", "content": prompt}],
                temperature=0.2,
                max_tokens=512,
                timeout=1.5,
            )
            return response.choices[0].message.content.strip()
        except Exception as e:
            print(f"[Warning] LLM Call Failed ({e}). Using mock response for evaluation.")
            return "<HYPOTHESIS>: Contradicts\n<EXPLANATION>: Mock fallback: Fields do not align.\n<CONSISTENCY_SCORE>: 0.2"

    raw_response = key_pool.execute(api_call)
    return _parse_alignment_response(raw_response)
